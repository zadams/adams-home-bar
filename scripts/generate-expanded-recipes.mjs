// Deduplicate by id within generated set; skip existing files
const seen = new Set()
const unique = []
for (const r of recipes) {
  if (seen.has(r.id) || existing.has(r.id)) continue
  // also skip if filename would collide with different naming
  seen.add(r.id)
  unique.push(r)
}

const registry = JSON.parse(fs.readFileSync(registryPath, 'utf8'))
let wrote = 0
const photoJobs = []

for (const raw of unique) {
  const { photoSearch, photoFamily, ...recipe } = raw
  const file = path.join(cocktailsDir, `${recipe.id}.json`)
  if (fs.existsSync(file)) continue
  fs.writeFileSync(file, JSON.stringify(recipe, null, 2) + '\n')
  wrote++

  const key = recipe.illustrationKey
  if (!registry[key]) {
    const familySrc =
      (photoFamily && registry[photoFamily]?.src) ||
      `/images/cocktails/photos/${photoFamily || key}.jpg`
    registry[key] = {
      src: `/images/cocktails/photos/${key}.jpg`,
      kind: 'photo',
      glassware: recipe.glassware,
      aspectRatio: '4 / 3',
      credit: 'TheCocktailDB',
      ingredients: recipe.ingredients
        .filter((i) => !i.optional)
        .slice(0, 4)
        .map((i) => i.ingredientId),
      photoSearch: photoSearch ?? recipe.name,
      photoFamily: photoFamily ?? null,
      fallbackSrc: familySrc,
    }
  }
  photoJobs.push({
    id: key,
    search: photoSearch ?? recipe.name,
    family: photoFamily,
  })
}

fs.writeFileSync(registryPath, JSON.stringify(registry, null, 2) + '\n')
fs.writeFileSync(
  path.join(root, 'scripts/photo-jobs.json'),
  JSON.stringify(photoJobs, null, 2) + '\n',
)

