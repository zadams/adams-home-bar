function addTemplateFamily(spiritId, templates) {
  const meta = spirits[spiritId]
  for (const t of templates) {
    recipes.push(
      cocktail({
        ...t,
        spirit: spiritId,
        name: t.nameIncludesSpirit === false ? t.name : t.name.replace('{S}', meta.label),
        description: t.description.replaceAll('{S}', meta.label.toLowerCase()),
        whyItWorks: t.whyItWorks.replaceAll('{S}', meta.label.toLowerCase()),
        tags: [...(t.tags ?? []), ...meta.tags],
        cocktailFamily: t.cocktailFamily ?? meta.family,
        recommendedBottles: recs(spiritId, t.rationale ?? `Showcases your ${meta.label}.`),
      }),
    )
  }
}

