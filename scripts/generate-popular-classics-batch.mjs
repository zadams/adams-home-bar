#!/usr/bin/env node
/**
 * Add a large batch of recognizable popular classics / modern standards.
 * Skips ids that already exist. Updates registry + illustration-manifest stubs.
 *
 *   node scripts/generate-popular-classics-batch.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const cocktailsDir = path.join(root, 'src/data/cocktails')
const registryPath = path.join(root, 'src/data/illustrations/registry.json')
const manifestPath = path.join(
  root,
  'src/data/illustrations/illustration-manifest.json',
)
const bottles = JSON.parse(
  fs.readFileSync(path.join(root, 'src/data/bottles/bottles.json'), 'utf8'),
)
const inventory = JSON.parse(
  fs.readFileSync(path.join(root, 'src/data/inventory/seed-inventory.json'), 'utf8'),
)

const bottleById = new Map(bottles.map((b) => [b.id, b]))
const bottlesByIngredient = new Map()
for (const item of inventory) {
  if (item.status === 'out' || !item.bottleId) continue
  const bottle = bottleById.get(item.bottleId)
  if (!bottle) continue
  for (const id of bottle.ingredientIds) {
    const list = bottlesByIngredient.get(id) ?? []
    if (!list.includes(bottle.id)) list.push(bottle.id)
    bottlesByIngredient.set(id, list)
  }
}

const existing = new Set(
  fs
    .readdirSync(cocktailsDir)
    .filter((f) => f.endsWith('.json'))
    .map((f) => JSON.parse(fs.readFileSync(path.join(cocktailsDir, f), 'utf8')).id),
)

function recs(spiritId, rationale = 'A strong match from your bar.') {
  const ids = bottlesByIngredient.get(spiritId) ?? []
  return ids.slice(0, 3).map((bottleId, i) => ({
    bottleId,
    rank: i + 1,
    rationale: i === 0 ? rationale : 'Also excellent from your shelf.',
  }))
}

function ing(ingredientId, amount, unit, extra = {}) {
  return {
    ingredientId,
    amount,
    unit,
    scaleMode: extra.scaleMode ?? 'linear',
    ...extra,
  }
}

function cocktail(def) {
  const id = def.id
  return {
    id,
    slug: def.slug ?? id,
    name: def.name,
    aliases: def.aliases ?? [],
    description: def.description,
    history: def.history,
    origin: def.origin,
    whyItWorks: def.whyItWorks,
    classifications: def.classifications,
    cocktailFamily: def.cocktailFamily,
    flavorProfiles: def.flavorProfiles,
    difficulty: def.difficulty ?? 'easy',
    preparationTime: def.preparationTime ?? 4,
    strength: def.strength ?? 'medium',
    glassware: def.glassware,
    ice: def.ice,
    garnish: def.garnish ?? [],
    illustrationKey: def.illustrationKey ?? id,
    ingredients: def.ingredients,
    steps: def.steps,
    techniqueNotes: def.techniqueNotes ?? [],
    recommendedBottles: def.recommendedBottles ?? (def.spirit ? recs(def.spirit) : []),
    substitutions: def.substitutions ?? [],
    variations: def.variations ?? [],
    relatedCocktailIds: def.relatedCocktailIds ?? [],
    seasonality: def.seasonality ?? ['year-round'],
    tags: def.tags ?? [],
    featuredBottleImages: [],
    photoSearch: def.photoSearch,
    photoFamily: def.photoFamily,
    artHint: def.artHint,
  }
}

