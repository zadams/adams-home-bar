const registry = JSON.parse(fs.readFileSync(registryPath, 'utf8'))
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'))
const manifestKeys = new Set(manifest.cocktails.map((c) => c.illustrationKey))

const COMPOSITION =
  'single centered hero cocktail, three-quarter view, generous safe area, no text, no bottle labels'
const BACKGROUND =
  'deep emerald-to-charcoal matte backdrop above a dark walnut bar, restrained brass accents'
const LIGHTING =
  'warm amber key from upper left, soft neutral fill, subtle rim light, realistic shadow'

function glassFromGlassware(gw) {
  const g = (gw || '').toLowerCase()
  if (g.includes('flute') || g.includes('champagne')) return 'flute'
  if (g.includes('coupe') || g.includes('martini')) return 'coupe'
  if (g.includes('copper')) return 'copper-mug'
  if (g.includes('julep')) return 'julep-cup'
  if (g.includes('collins') || g.includes('highball')) return 'highball'
  if (g.includes('wine')) return 'wine'
  if (g.includes('mug')) return 'mug'
  if (g.includes('shot')) return 'shot'
  if (g.includes('hurricane')) return 'hurricane'
  return 'rocks'
}

function buildManifestEntry(recipe) {
  const hint = recipe.artHint ?? {}
  const [paletteName, paletteHex] = hint.palette ?? ['warm-amber', '#B06932']
  const key = recipe.illustrationKey
  return {
    id: recipe.id,
    slug: recipe.slug,
    name: recipe.name,
    illustrationKey: key,
    cocktailFamily: recipe.cocktailFamily,
    classifications: recipe.classifications,
    flavorProfiles: recipe.flavorProfiles,
    ingredientIds: recipe.ingredients
      .filter((i) => !i.optional)
      .map((i) => i.ingredientId),
    artDirection: {
      template: hint.template ?? 'editorial-standard',
      glass: hint.glass ?? glassFromGlassware(recipe.glassware),
      sourceGlassware: recipe.glassware,
      ice: hint.ice ?? recipe.ice,
      garnish: hint.garnish ?? (recipe.garnish[0] ?? 'none'),
      liquidPalette: { name: paletteName, hex: paletteHex },
      composition: COMPOSITION,
      background: BACKGROUND,
      lighting: LIGHTING,
      output: {
        master: `cocktails/masters/${key}.png`,
        runtime: `cocktails/webp/${key}.webp`,
        thumbnail: `cocktails/thumbs/${key}.webp`,
      },
    },
  }
}

let wrote = 0
const newIds = []

for (const raw of unique) {
  const { photoSearch, photoFamily, artHint, ...recipe } = raw
  const file = path.join(cocktailsDir, `${recipe.id}.json`)
  if (fs.existsSync(file)) continue
  fs.writeFileSync(file, JSON.stringify(recipe, null, 2) + '\n')
  wrote++
  newIds.push(recipe.id)

  const key = recipe.illustrationKey
  if (!registry[key]) {
    const familySrc =
      (photoFamily && registry[photoFamily]?.src) ||
      `/images/cocktails/photos/${photoFamily || key}.jpg`
    registry[key] = {
      src: `/images/cocktails/photos/${key}.jpg`,
      kind: 'photo',
      glassware: recipe.glassware,
      aspectRatio: '4 / 3',
      credit: 'TheCocktailDB',
      ingredients: recipe.ingredients
        .filter((i) => !i.optional)
        .slice(0, 4)
        .map((i) => i.ingredientId),
      photoSearch: photoSearch ?? recipe.name,
      photoFamily: photoFamily ?? null,
      fallbackSrc: familySrc,
      pending: true,
    }
  }

  if (!manifestKeys.has(key)) {
    manifest.cocktails.push(buildManifestEntry({ ...recipe, artHint }))
    manifestKeys.add(key)
  }
}

manifest.cocktailCount = manifest.cocktails.length
